#!/usr/bin/env python3
"""Build and install host instruction files that cannot import rules/core.md.

Usage: build.py (--build | --install | --check) [--host NAME]... [--all-hosts] [--lang en|zh]
  (no args) print this help and exit; nothing is written. Unknown options are refused the same way.
  --build   write rules/build/<host>/AGENTS.md = core.md + hosts/<host>.md for hosts in TARGETS
  --install build, require interactive confirmation ("CONFIRM" by default) on a TTY (no --yes bypass), then copy each built file to its live location (backup kept next to it)
  --check   report which live host files are out of date relative to rules/ (read-only)

Hosts with an import mechanism (Claude Code: @path; opencode: opencode.json instructions; Gemini:
@path) are NOT concatenated with core here. Their hosts/<host>.md carries one section per platform,
and --install --host <host> writes the common part plus this platform's section only (see
for_platform) to the live file in PLATFORM_LIVE.

--install --host claude also installs the hooks that enforce the rules (CLAUDE_HOOKS): copies
rules/hooks/<file> to ~/.claude/hooks/ and registers each one in ~/.claude/settings.json, so a new
machine can install the applicable hooks with the same command.
"""
import argparse
import json
import os
import pathlib
import re
import shutil
import sys
import time

ROOT = pathlib.Path(__file__).resolve().parent
CORE = ROOT / "core.md"
HOSTS = ROOT / "hosts"
BUILD = ROOT / "build"
HOME = pathlib.Path.home()

# host name -> live file that receives concatenated core + delta (when a host has no @import)
TARGETS = {
    "openclaw": HOME / ".openclaw" / "workspace" / "AGENTS.md",
}

BANNER = {
    "en": "<!-- Generated by HSkills rules/build.py: rules/core.md + rules/hosts/{host}.md. Edit the sources and rerun build.py --install. -->\n\n",
    "zh": "<!-- 由 HSkills rules/build.py 生成：rules/core.md + rules/hosts/{host}.md。请修改源文件后重跑 build.py --install。 -->\n\n",
}


def _message(lang, en, zh):
    return zh if lang == "zh" else en


CLAUDE_LIVE = HOME / ".claude" / "CLAUDE.md"
PLATFORMS = {"win32": "Windows", "darwin": "macOS", "linux": "Linux"}  # sys.platform -> heading
# hosts that import core themselves: host -> live file that receives hosts/<host>.md for this platform
PLATFORM_LIVE = {
    "claude": CLAUDE_LIVE,
    "opencode": HOME / ".config" / "opencode" / "AGENTS.md",
    "gemini": HOME / ".gemini" / "GEMINI.md",
}

CLAUDE_HOOK_DIR = HOME / ".claude" / "hooks"
CLAUDE_SETTINGS = HOME / ".claude" / "settings.json"
# (event, matcher, file in rules/hooks, platforms it applies to or None for all, timeout seconds)
CLAUDE_HOOKS = [
    ("SessionStart", None, "daybook-limit.mjs", None, None),
    ("PreToolUse", "Bash|PowerShell", "confirm-push.mjs", None, 15),
    ("PreToolUse", "Bash", "block-rm.py", {"linux", "darwin"}, 10),  # Windows 的 Bash 工具另有删除办法
]
# Optional external hooks are registered only when their repository exists locally.
# AI_TODO_REPO overrides the portable default ~/ai-todo.
AI_TODO_DEFAULT = HOME / "ai-todo"
AI_TODO_SUMMARY = pathlib.Path(os.environ.get("AI_TODO_REPO") or AI_TODO_DEFAULT) / "bin" / "ai-todo-summary.py"


def for_platform(host, platform=None):
    """hosts/<host>.md minus the other platforms' sections. Each platform section is a level-2
    heading named exactly as in PLATFORMS and runs to the next level-2 heading or the end."""
    keep = PLATFORMS[platform or sys.platform]
    parts = re.split(r"(?m)^(?=## )", (HOSTS / f"{host}.md").read_text(encoding="utf-8"))
    kept = [p for p in parts
            if (p.splitlines() or [""])[0][3:].strip() not in set(PLATFORMS.values()) - {keep}]
    return ("".join(kept).rstrip("\n") + "\n").replace("__HSKILLS_ROOT__", ROOT.parent.as_posix())


def build_text(host, lang="en"):
    delta = for_platform(host)
    core = CORE.read_text(encoding="utf-8")
    return (BANNER[lang].format(host=host) + core.rstrip("\n") + "\n\n---\n\n" + delta.lstrip("\n")).replace("__HSKILLS_ROOT__", ROOT.parent.as_posix())


def build(host, lang="en"):
    out = BUILD / host / "AGENTS.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(build_text(host, lang), encoding="utf-8")
    return out


def install(host, built):
    target = TARGETS[host]
    if target.exists():
        stamp = time.strftime("%Y%m%d-%H%M%S")
        shutil.copy2(target, target.with_name(f"{target.name}.bak-{stamp}"))
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(built, target)
    return target


def _interpreter(file):
    if file.endswith((".mjs", ".js")):
        return "node"
    return f'"{sys.executable}"' if sys.platform == "win32" else "python3"


def _wanted_claude_hooks():
    """(event, matcher, marker, command, timeout) for every hook this machine should have."""
    wanted = []
    for event, matcher, file, platforms, timeout in CLAUDE_HOOKS:
        if platforms and sys.platform not in platforms:
            continue
        target = (CLAUDE_HOOK_DIR / file).as_posix()
        wanted.append((event, matcher, file, f'{_interpreter(file)} "{target}"', timeout))
    if AI_TODO_SUMMARY.is_file():
        wanted.append(("SessionStart", None, "ai-todo-summary.py",
                       f'{_interpreter("x.py")} "{AI_TODO_SUMMARY.as_posix()}"', 15))
    return wanted


def _find_hook(settings, event, marker):
    for entry in settings.get("hooks", {}).get(event, []):
        for hook in entry.get("hooks", []):
            if marker in str(hook.get("command", "")):
                return entry, hook
    return None, None


def install_claude_hooks(lang="en"):
    """Copy rules/hooks into ~/.claude/hooks and register them in settings.json. Re-running is safe:
    an entry whose command already names the same script is updated in place, not duplicated."""
    stamp = time.strftime("%Y%m%d-%H%M%S")
    lines = []
    CLAUDE_HOOK_DIR.mkdir(parents=True, exist_ok=True)
    for _event, _matcher, file, platforms, _timeout in CLAUDE_HOOKS:
        if platforms and sys.platform not in platforms:
            continue
        source, target = ROOT / "hooks" / file, CLAUDE_HOOK_DIR / file
        if target.exists() and target.read_bytes() == source.read_bytes():
            continue
        if target.exists():
            shutil.copy2(target, target.with_name(f"{file}.bak-{stamp}"))
        shutil.copy2(source, target)
        lines.append(_message(lang, f"hook file: copied {file}", f"hook 文件：已复制 {file}"))

    settings = json.loads(CLAUDE_SETTINGS.read_text(encoding="utf-8")) if CLAUDE_SETTINGS.exists() else {}
    changed = False
    for event, matcher, marker, command, timeout in _wanted_claude_hooks():
        wanted = {"type": "command", "command": command, **({"timeout": timeout} if timeout else {})}
        entry, hook = _find_hook(settings, event, marker)
        if hook is None:
            new_entry = {**({"matcher": matcher} if matcher else {}), "hooks": [wanted]}
            settings.setdefault("hooks", {}).setdefault(event, []).append(new_entry)
            lines.append(_message(lang, f"hook: registered {marker} on {event}", f"hook：已将 {marker} 注册到 {event}"))
            changed = True
        else:
            expected_matcher = matcher or None
            if entry.get("matcher") != expected_matcher or any(hook.get(k) != v for k, v in wanted.items()):
                if expected_matcher:
                    entry["matcher"] = expected_matcher
                else:
                    entry.pop("matcher", None)
                hook.update(wanted)
                lines.append(_message(lang, f"hook: updated {marker} on {event}", f"hook：已更新 {event} 的 {marker}"))
                changed = True
    if not AI_TODO_SUMMARY.is_file():
        lines.append(_message(lang, f"hook: ai-todo not on this machine ({AI_TODO_SUMMARY}), its summary hook skipped",
                              f"hook：本机未找到 ai-todo（{AI_TODO_SUMMARY}），已跳过摘要 hook"))
    if changed:
        if CLAUDE_SETTINGS.exists():
            shutil.copy2(CLAUDE_SETTINGS, CLAUDE_SETTINGS.with_name(f"settings.json.bak-{stamp}"))
        CLAUDE_SETTINGS.write_text(json.dumps(settings, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return lines or [_message(lang, "hooks: already up to date", "hooks：已是最新")]


def check_claude_hooks(lang="en"):
    stale = 0
    settings = json.loads(CLAUDE_SETTINGS.read_text(encoding="utf-8")) if CLAUDE_SETTINGS.exists() else {}
    for event, _matcher, file, platforms, _timeout in CLAUDE_HOOKS:
        if platforms and sys.platform not in platforms:
            continue
        target = CLAUDE_HOOK_DIR / file
        if not target.exists() or target.read_bytes() != (ROOT / "hooks" / file).read_bytes():
            print(_message(lang, f"hook {file}: STALE or MISSING in {CLAUDE_HOOK_DIR} (run build.py --install --host claude)",
                           f"hook {file}：{CLAUDE_HOOK_DIR} 中的文件已过期或缺失（运行 build.py --install --host claude）")); stale += 1
    for event, matcher, marker, _command, _timeout in _wanted_claude_hooks():
        entry, hook = _find_hook(settings, event, marker)
        if hook is None:
            print(_message(lang, f"hook {marker}: not registered on {event} in {CLAUDE_SETTINGS}",
                           f"hook {marker}：尚未在 {CLAUDE_SETTINGS} 的 {event} 中注册")); stale += 1
        elif entry.get("matcher") != (matcher or None):
            print(_message(lang, f"hook {marker}: matcher STALE on {event} in {CLAUDE_SETTINGS} (run build.py --install --host claude)",
                           f"hook {marker}：{CLAUDE_SETTINGS} 中 {event} 的匹配条件已过期（运行 build.py --install --host claude）")); stale += 1
    if not stale:
        print(_message(lang, "claude hooks: ok", "claude hooks：正常"))
    return stale


def check(hosts=None, lang="en"):
    """Report which live host files are out of date relative to rules/."""
    wanted_hosts = set(hosts) if hosts else set([*PLATFORM_LIVE, *TARGETS])
    stale = check_claude_hooks(lang) if "claude" in wanted_hosts else 0
    for host, target in PLATFORM_LIVE.items():
        if host not in wanted_hosts:
            continue
        if not target.exists():
            print(_message(lang, f"{host}: MISSING {target}", f"{host}：缺失 {target}")); stale += 1
        elif target.read_text(encoding="utf-8").replace("\r\n", "\n") != for_platform(host):
            print(_message(lang, f"{host}: STALE {target} (run build.py --install --host {host})",
                           f"{host}：已过期 {target}（运行 build.py --install --host {host}）")); stale += 1
        else:
            print(_message(lang, f"{host}: ok ({target}, {PLATFORMS[sys.platform]} section)",
                           f"{host}：正常（{target}，{PLATFORMS[sys.platform]} 分节）"))
    if "opencode" in wanted_hosts:
        cfg = HOME / ".config" / "opencode" / "opencode.json"
        try:
            instr = json.loads(cfg.read_text(encoding="utf-8")).get("instructions", [])
            if not isinstance(instr, list):
                print(_message(lang, 'opencode.json: "instructions" must be a list', 'opencode.json："instructions" 必须是列表'))
                stale += 1
            else:
                hit = any(pathlib.Path(i).resolve() == CORE.resolve() for i in instr
                          if isinstance(i, str) and not i.startswith("http"))
                print(_message(lang, f"opencode.json instructions -> core: {'ok' if hit else 'MISSING'}",
                               f"opencode.json instructions -> core：{'正常' if hit else '缺失'}")); stale += 0 if hit else 1
        except FileNotFoundError:
            print(_message(lang, f'opencode.json: not configured yet ({cfg} not found; manually add {CORE.resolve()} to "instructions" to enable)',
                           f'opencode.json：尚未配置（未找到 {cfg}；请手动将 {CORE.resolve()} 加入 "instructions" 以启用）')); stale += 1
        except Exception as e:  # noqa: BLE001
            print(_message(lang, f"opencode.json: unreadable ({e})", f"opencode.json：无法读取（{e}）")); stale += 1
    for host in TARGETS:
        if host not in wanted_hosts:
            continue
        target = TARGETS[host]
        if not target.exists():
            print(_message(lang, f"{host}: MISSING {target}", f"{host}：缺失 {target}")); stale += 1
        elif target.read_text(encoding="utf-8").replace("\r\n", "\n") != build_text(host, lang):
            print(_message(lang, f"{host}: STALE {target} (run build.py --install --host {host})",
                           f"{host}：已过期 {target}（运行 build.py --install --host {host}）")); stale += 1
        else:
            print(_message(lang, f"{host}: ok ({target})", f"{host}：正常（{target}）"))
    return 1 if stale else 0


def _cli_lang(argv):
    for i, arg in enumerate(argv):
        if arg == "--lang" and i + 1 < len(argv):
            return argv[i + 1]
        if arg.startswith("--lang="):
            return arg.split("=", 1)[1]
    return os.environ.get("HSKILLS_LANG", "en")


class Parser(argparse.ArgumentParser):
    def __init__(self, *args, cli_lang="en", **kwargs):
        self._cli_lang = cli_lang if cli_lang in ("en", "zh") else "en"
        super().__init__(*args, **kwargs)

    def error(self, message):
        self.print_usage(sys.stderr)
        self.exit(2, _message(
            self._cli_lang,
            f"build.py: {message}. Nothing was written; run build.py --help for the full usage.\n",
            f"build.py：{message}。未写入任何文件；运行 build.py --help --lang zh 查看完整用法。\n",
        ))


def parse_args(argv):
    cli_lang = _cli_lang(argv)
    parser = Parser(
        prog="build.py",
        cli_lang=cli_lang,
        description=_message(
            cli_lang,
            __doc__,
            "将 HSkills 规则编译并安装到各宿主（claude / gemini / openclaw / opencode）。",
        ),
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--build", action="store_true", help=_message(cli_lang, "write rules/build/<host>/AGENTS.md only", "仅生成到仓库内 rules/build/<host>/"))
    mode.add_argument("--install", action="store_true", help=_message(cli_lang, "build and install to the live locations", "构建并安装到宿主全局配置位置"))
    mode.add_argument("--check", action="store_true", help=_message(cli_lang, "read-only staleness report", "只读检查各宿主配置是否过期"))
    parser.add_argument("--host", action="append", choices=sorted([*TARGETS, *PLATFORM_LIVE]),
                        help=_message(cli_lang, "limit --build / --install / --check to this host; repeatable (required with --install unless --all-hosts is set)", "限定目标宿主，可重复传入（--install 时除非带 --all-hosts，否则必选）"))
    parser.add_argument("--all-hosts", action="store_true",
                        help=_message(cli_lang, "with --install, explicitly install to all 4 configured hosts", "配合 --install，显式安装到全部 4 个宿主"))
    parser.add_argument("--lang", choices=("en", "zh"), default=os.environ.get("HSKILLS_LANG", "en"),
                        help=_message(cli_lang, "output language (default: HSKILLS_LANG or en); zh uses the Chinese confirmation phrase", "输出语言（默认取 HSKILLS_LANG 或 en）；zh 将使用中文确认词"))
    if not argv:
        parser.print_help()
        sys.exit(0)
    args = parser.parse_args(argv)
    if args.lang not in ("en", "zh"):
        parser.error(_message(cli_lang, "HSKILLS_LANG must be en or zh (or override it with --lang)", "HSKILLS_LANG 必须为 en 或 zh（或通过 --lang 覆盖）"))
    if args.install and not args.host and not args.all_hosts:
        parser.error(_message(cli_lang, "--install requires --host <host> (or --all-hosts to install to all 4 hosts)", "--install 需要指定 --host <宿主>（或传 --all-hosts 安装到全部 4 个宿主）"))
    return args


INSTALL_CONFIRM_PHRASE = {"en": "CONFIRM", "zh": "我确认"}


def _clone_path_warning(lang):
    return _message(lang,
                    "Warning: CLAUDE.md/GEMINI.md embed this clone's absolute path (__HSKILLS_ROOT__). Keep the clone in a permanent location; re-run --install if it is moved or deleted.",
                    "提醒：CLAUDE.md/GEMINI.md 内嵌此克隆的绝对路径（__HSKILLS_ROOT__）。请将克隆保留在固定位置；移动或删除后必须重新运行 --install。")


def _ensure_safe_console_streams():
    for stream in (sys.stdout, sys.stderr):
        if stream is not None and hasattr(stream, "reconfigure"):
            try:
                stream.reconfigure(errors="replace")
            except Exception:  # noqa: BLE001
                pass


def _install_targets(hosts, lang="en"):
    targets = []
    for host in hosts:
        if host in PLATFORM_LIVE:
            targets.append(str(PLATFORM_LIVE[host]))
            if host == "claude":
                targets.append(_message(lang, f"{CLAUDE_HOOK_DIR} and {CLAUDE_SETTINGS} (copy and register Claude hooks)",
                                        f"{CLAUDE_HOOK_DIR} 与 {CLAUDE_SETTINGS}（复制并注册 Claude hooks）"))
        elif host in TARGETS:
            targets.append(str(TARGETS[host]))
    return targets


def confirm_install(hosts, lang="en"):
    """Require a human on an interactive TTY to type the selected phrase before writing."""
    _ensure_safe_console_streams()
    print(_message(lang, "The following global configuration will be changed (adjacent .bak-<timestamp> backups do not replace a full configuration backup):",
                   "即将修改以下本机全局配置（覆盖前会自动在旁生成 .bak-<时间戳> 副本，但不能替代完整配置备份）："))
    for item in _install_targets(hosts, lang):
        print(f"  - {item}")
    print(_clone_path_warning(lang))
    print(_message(lang, "\nHave you backed up your local configuration? Do not use this tool without a backup.",
                   "\n你是否做好了本机配置的备份，如果不备份建议不使用这个工具"), flush=True)
    if not sys.stdin or not sys.stdin.isatty():
        print(
            _message(lang, "build.py: --install requires the user to confirm manually in a real interactive terminal; non-interactive pipes and automated bypasses are not supported. Nothing was written.",
                     "build.py: --install 必须在真实交互终端中由使用者本人手动确认，不支持非交互管道或自动化绕过；本次未修改任何文件。"),
            file=sys.stderr,
            flush=True,
        )
        return 2
    try:
        phrase = INSTALL_CONFIRM_PHRASE[lang]
        answer = input(_message(lang, f'Type "{phrase}" and press Enter to continue (anything else aborts): ',
                                f"请输入「{phrase}」后按回车继续（其他任意输入均立即中止）："))
    except (EOFError, KeyboardInterrupt, UnicodeDecodeError):
        print(_message(lang, "\nCancelled. Nothing was written.", "\n已取消，未修改任何文件。"), file=sys.stderr)
        return 1
    if answer.strip() != phrase:
        print(_message(lang, "Confirmation phrase mismatch. Aborted; nothing was written.", "确认口令不匹配，已中止，未修改任何文件。"), file=sys.stderr)
        return 1
    return 0


def main(argv):
    _ensure_safe_console_streams()
    args = parse_args(argv)
    lang = args.lang
    if args.check:
        return check(args.host, lang)
    do_install = args.install
    hosts = list(dict.fromkeys(args.host or sorted([*PLATFORM_LIVE, *TARGETS])))
    if do_install:
        refuse_code = confirm_install(hosts, lang)
        if refuse_code:
            return refuse_code
    for host in hosts:
        if host in PLATFORM_LIVE:
            live = PLATFORM_LIVE[host]
            text = for_platform(host)
            line = _message(lang, f"{host}: {PLATFORMS[sys.platform]} section", f"{host}：{PLATFORMS[sys.platform]} 分节")
            if not do_install:
                preview = BUILD / host / live.name
                preview.parent.mkdir(parents=True, exist_ok=True)
                preview.write_text(text, encoding="utf-8")
                line += _message(lang, f" -> built {preview.relative_to(ROOT)} ({preview.stat().st_size} bytes)",
                                 f" -> 已生成 {preview.relative_to(ROOT)}（{preview.stat().st_size} 字节）")
            else:
                if live.exists():
                    stamp = time.strftime("%Y%m%d-%H%M%S")
                    shutil.copy2(live, live.with_name(f"{live.name}.bak-{stamp}"))
                live.parent.mkdir(parents=True, exist_ok=True)
                live.write_text(text, encoding="utf-8")
                line += _message(lang, f" -> installed {live}", f" -> 已安装 {live}")
            print(line)
            if do_install and host == "claude":
                for hook_line in install_claude_hooks(lang):
                    print(f"claude: {hook_line}")
            continue
        built = build(host, lang)
        size = built.stat().st_size
        line = _message(lang, f"{host}: built {built.relative_to(ROOT)} ({size} bytes)", f"{host}：已生成 {built.relative_to(ROOT)}（{size} 字节）")
        if do_install:
            target = install(host, built)
            line += _message(lang, f" -> installed {target}", f" -> 已安装 {target}")
        print(line)
    if do_install:
        print(_clone_path_warning(lang))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
